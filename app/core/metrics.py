"""
Application Telemetry & Prometheus Metrics Collection.

Provides thread-safe metrics recording for bulk certificate ingestion,
processing duration, PDF rendering throughput, queue health, and API requests.
Exposes data in standard Prometheus text format (# HELP / # TYPE) and JSON.
"""

import threading
from typing import Any


class MetricsRegistry:
    """Thread-safe Prometheus-compatible metrics registry."""

    def __init__(self) -> None:
        self._lock = threading.Lock()

        # Job Counters
        self.jobs_submitted_total = 0
        self.jobs_completed_total = 0
        self.jobs_failed_total = 0

        # Certificate Counters
        self.certificates_success_total = 0
        self.certificates_failure_total = 0

        # Histograms / Summaries (count, sum)
        self.pdf_render_count = 0
        self.pdf_render_sum_seconds = 0.0

        self.job_duration_count = 0
        self.job_duration_sum_seconds = 0.0

        # API Request Counters: (method, path, status_code) -> count
        self.http_requests_total: dict[tuple[str, str, int], int] = {}
        self.http_request_sum_seconds: dict[tuple[str, str], float] = {}

    def record_job_submitted(self) -> None:
        with self._lock:
            self.jobs_submitted_total += 1

    def record_job_completed(
        self, duration_seconds: float, success_count: int, failure_count: int
    ) -> None:
        with self._lock:
            self.jobs_completed_total += 1
            self.job_duration_count += 1
            self.job_duration_sum_seconds += max(0.0, duration_seconds)
            self.certificates_success_total += max(0, success_count)
            self.certificates_failure_total += max(0, failure_count)

    def record_job_failed(self, duration_seconds: float) -> None:
        with self._lock:
            self.jobs_failed_total += 1
            self.job_duration_count += 1
            self.job_duration_sum_seconds += max(0.0, duration_seconds)

    def record_certificate_rendered(self, render_time_seconds: float, success: bool = True) -> None:
        with self._lock:
            if success:
                self.certificates_success_total += 1
            else:
                self.certificates_failure_total += 1
            self.pdf_render_count += 1
            self.pdf_render_sum_seconds += max(0.0, render_time_seconds)

    def record_http_request(
        self, method: str, path: str, status_code: int, duration_seconds: float
    ) -> None:
        with self._lock:
            key = (method, path, status_code)
            self.http_requests_total[key] = self.http_requests_total.get(key, 0) + 1

            latency_key = (method, path)
            self.http_request_sum_seconds[latency_key] = (
                self.http_request_sum_seconds.get(latency_key, 0.0) + duration_seconds
            )

    def to_dict(self) -> dict[str, Any]:
        """Return metrics as a dictionary for JSON reporting."""
        with self._lock:
            avg_pdf_render = (
                (self.pdf_render_sum_seconds / self.pdf_render_count)
                if self.pdf_render_count > 0
                else 0.0
            )
            avg_job_duration = (
                (self.job_duration_sum_seconds / self.job_duration_count)
                if self.job_duration_count > 0
                else 0.0
            )

            return {
                "jobs": {
                    "submitted_total": self.jobs_submitted_total,
                    "completed_total": self.jobs_completed_total,
                    "failed_total": self.jobs_failed_total,
                    "avg_duration_seconds": round(avg_job_duration, 4),
                },
                "certificates": {
                    "success_total": self.certificates_success_total,
                    "failure_total": self.certificates_failure_total,
                    "total_generated": self.certificates_success_total
                    + self.certificates_failure_total,
                    "avg_render_seconds": round(avg_pdf_render, 4),
                },
                "http_requests_total": sum(self.http_requests_total.values()),
            }

    def to_prometheus_text(self) -> str:
        """Export metrics formatted in Prometheus plain-text exposition syntax."""
        with self._lock:
            lines = [
                "# HELP certificate_jobs_total Total bulk certificate jobs by state.",
                "# TYPE certificate_jobs_total counter",
                f'certificate_jobs_total{{state="submitted"}} {self.jobs_submitted_total}',
                f'certificate_jobs_total{{state="completed"}} {self.jobs_completed_total}',
                f'certificate_jobs_total{{state="failed"}} {self.jobs_failed_total}',
                "",
                "# HELP certificates_generated_total Total individual certificates generated by outcome.",
                "# TYPE certificates_generated_total counter",
                f'certificates_generated_total{{outcome="success"}} {self.certificates_success_total}',
                f'certificates_generated_total{{outcome="failure"}} {self.certificates_failure_total}',
                "",
                "# HELP certificate_pdf_render_duration_seconds Individual PDF rendering latency summary.",
                "# TYPE certificate_pdf_render_duration_seconds summary",
                f"certificate_pdf_render_duration_seconds_count {self.pdf_render_count}",
                f"certificate_pdf_render_duration_seconds_sum {self.pdf_render_sum_seconds:.4f}",
                "",
                "# HELP bulk_job_duration_seconds Total job processing duration summary.",
                "# TYPE bulk_job_duration_seconds summary",
                f"bulk_job_duration_seconds_count {self.job_duration_count}",
                f"bulk_job_duration_seconds_sum {self.job_duration_sum_seconds:.4f}",
                "",
                "# HELP http_requests_total HTTP request counts by method, path, and status.",
                "# TYPE http_requests_total counter",
            ]

            for (method, path, status_code), count in sorted(self.http_requests_total.items()):
                lines.append(
                    f'http_requests_total{{method="{method}",path="{path}",status="{status_code}"}} {count}'
                )

            lines.append("")
            return "\n".join(lines)


# Singleton Registry
metrics_registry = MetricsRegistry()
